/**
 * 会社名から公式DHVポートフォリオ情報を照合するユーティリティ
 */
export function getDHVPortfolioInfo(companyName: string): DHVPortfolioCompany | undefined {
  const clean = companyName.replace(/(株式会社|合同会社|有限会社|Inc\.|Co\.,\s*Ltd\.|LLC)/g, '').trim().toLowerCase();
  return DHV_PORTFOLIO_MASTER.find((item) => {
    const itemClean = item.companyName.replace(/(株式会社|合同会社|有限会社|Inc\.|Co\.,\s*Ltd\.|LLC)/g, '').trim().toLowerCase();
    return itemClean === clean || (item.companyNameEn && item.companyNameEn.toLowerCase().includes(clean)) || clean.includes(itemClean);
  });
}
